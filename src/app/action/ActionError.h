//
// ActionError.h - Actionが返す失敗の重大度(全Action共通の語彙)
//
// 失敗の分類(コード)はAction個別だが、重大度はアプリ横断で同じ意味を持たせる。
// UIはコードそのものではなく重大度を見て、識別子を表示するかどうかを決める。
//
#pragma once

namespace rs::app {

enum class ErrorSeverity {
    // ユーザーが入力や対象を直して再試行できる失敗。パスの誤り、内容が不正なファイルなど。
    // ユーザー向けには文言だけを出し、機械可読の識別子は見せない。
    Recoverable,
    // プログラム側の不具合・想定外の例外・処理を続行できない事態。不具合報告で識別子が
    // 要るため、ユーザー向けにも識別子を併記する。安全終了を伴う失敗もここに含む。
    Critical,
};

} // namespace rs::app
